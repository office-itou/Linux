# --- python library ----------------------------------------------------------
from pathlib import Path

# --- my library --------------------------------------------------------------
from common.utils import (
    addpath,
    cat,
    debug_logger,
    find_serivce,
    fread,
    fwrite,
    get_caller_name,
    handle_fatal_error,
    message_info,
    restart_user_service,
)

# --- import module -----------------------------------------------------------
from autoinst_fn_file_backup import file_backup, file_origin


# --- class and function ------------------------------------------------------
@debug_logger
def setup_wireplumber(info_syst) -> None:
    _caller = get_caller_name()
    _data = info_syst.data
    _tget_path: Path = getattr(_data, "tget_path", None)
    # --- check service -------------------------------------------------------
    _srvc_name: str = "wireplumber.service"
    _srvc_path: Path = find_serivce(tget_path=_tget_path, srvc_name=_srvc_name)
    if not _srvc_path or not _srvc_path.exists():
        message_info(_caller, f"{'skip':<10}:wireplumber", omit=True)
        return
    # --- memo ----------------------------------------------------------------
    # https://gitlab.freedesktop.org/pipewire/pipewire/-/wikis/Troubleshooting
    try:
        message_info(_caller, f"{'setup':<10}:wireplumber", omit=True)
        _tags_text: str = "# Generated by user script"
        # --- main.conf -------------------------------------------------------
        _conf_path: Path = addpath(
            base=_tget_path,
            path=Path("/usr/share/wireplumber/main.lua.d/50-alsa-config.lua"),
        )
        if _conf_path.exists():
            # --- memo --------------------------------------------------------
            # debian-12
            #   wireplumber: 0.4.13
            #   pipewire   : 0.3.65
            # --- alsa: 51-alsa-config.lua ------------------------------------
            # stuttering audio (in virtual machine)
            _conf_path: Path = addpath(
                base=_tget_path,
                path=Path("/etc/wireplumber/main.lua.d/51-alsa-config.lua"),
            )
            file_backup(info_syst=info_syst, orig_path=_conf_path)
            file_origin(info_syst=info_syst, orig_path=_conf_path)
            _read_text: str = (
                fread(src_path=_conf_path, text=True) + "\n"
                if _conf_path.exists()
                else ""
            )
            if "alsa_monitor.properties" not in _read_text:
                _writ_text: str = cat(r"""
					alsa_monitor.properties = {
					  ["vm.node.defaults"] = {
					    ["api.alsa.period-size"] = 1024,
					    ["api.alsa.headroom"] = 16384,
					  },
					}
				""")  # noqa: E101
                fwrite(
                    dest_path=_conf_path,
                    data=_writ_text,
                    text=True,
                    backup=False,
                    append=True,
                )
                file_backup(info_syst=info_syst, orig_path=_conf_path, mode="init")
            # --- bluetooth: 51-bluez-config.lua ------------------------------
            # headset disabled
            _conf_path: Path = addpath(
                base=_tget_path,
                path=Path("/etc/wireplumber/bluetooth.lua.d/51-bluez-config.lua"),
            )
            file_backup(info_syst=info_syst, orig_path=_conf_path)
            file_origin(info_syst=info_syst, orig_path=_conf_path)
            _read_text: str = (
                fread(src_path=_conf_path, text=True) + "\n"
                if _conf_path.exists()
                else ""
            )
            if "bluez_monitor.properties" not in _read_text:
                _writ_text: str = cat(r"""
					bluez_monitor.properties = {
					  ["bluez5.headset-roles"] = "[ ]",
					  ["bluez5.hfphsp-backend"] = "none"
					}
					
					bluez_monitor.rules = {
					  {
					    matches = {
					      {
					        -- Matches all sources.
					        { "node.name", "matches", "bluez_input.*" },
					      },
					      {
					        -- Matches all sinks.
					        { "node.name", "matches", "bluez_output.*" },
					      },
					    },
					    apply_properties = {
					      ["bluez5.auto-connect"] = "[ a2dp_sink ]",
					      ["bluez5.hw-volume"]    = "[ a2dp_sink ]",
					    },
					  },
					}
				""")  # noqa: E101
                fwrite(
                    dest_path=_conf_path,
                    data=_writ_text,
                    text=True,
                    backup=False,
                    append=True,
                )
                file_backup(info_syst=info_syst, orig_path=_conf_path, mode="init")
        else:
            # --- memo --------------------------------------------------------
            # debian-13
            #   wireplumber: 0.5.8
            #   pipewire   : 1.4.2
            # --- alsa: 50-alsa-suspend.conf ----------------------------------
            # loud pops when starting a sound
            _conf_path: Path = addpath(
                base=_tget_path,
                path=Path("/etc/wireplumber/wireplumber.conf.d/50-alsa-suspend.conf"),
            )
            file_backup(info_syst=info_syst, orig_path=_conf_path)
            file_origin(info_syst=info_syst, orig_path=_conf_path)
            _read_text: str = (
                fread(src_path=_conf_path, text=True) + "\n"
                if _conf_path.exists()
                else ""
            )
            if "monitor.alsa.rules" not in _read_text:
                _writ_text: str = cat(r"""
					monitor.alsa.rules = [
					  {
					    matches = [
					      # This matches the value of the 'node.name' property of the node.
					      {
					        node.name = "~alsa_output.*"
					      }
					    ]
					    actions = {
					      update-props = {
					        session.suspend-timeout-seconds = 0
					      }
					    }
					  }
					]
				""")  # noqa: E101, E501
                fwrite(
                    dest_path=_conf_path,
                    data=_writ_text,
                    text=True,
                    backup=False,
                    append=True,
                )
                file_backup(info_syst=info_syst, orig_path=_conf_path, mode="init")
            # --- alsa: 50-alsa-config.conf -----------------------------------
            # stuttering audio (in virtual machine)
            _conf_path: Path = addpath(
                base=_tget_path,
                path=Path("/etc/wireplumber/wireplumber.conf.d/50-alsa-config.conf"),
            )
            file_backup(info_syst=info_syst, orig_path=_conf_path)
            file_origin(info_syst=info_syst, orig_path=_conf_path)
            _read_text: str = (
                fread(src_path=_conf_path, text=True) + "\n"
                if _conf_path.exists()
                else ""
            )
            if "monitor.alsa.rules" not in _read_text:
                _writ_text: str = cat(r"""
					monitor.alsa.rules = [
					  {
					    matches = [
					      # This matches the value of the 'node.name' property of the node.
					      {
					        node.name = "~alsa_output.*"
					      }
					    ]
					    actions = {
					      # Apply all the desired node specific settings here.
					      update-props = {
					        api.alsa.period-size   = 1024
					        api.alsa.headroom      = 16384
					      }
					    }
					  }
					]
				""")  # noqa: E101, E501
                fwrite(
                    dest_path=_conf_path,
                    data=_writ_text,
                    text=True,
                    backup=False,
                    append=True,
                )
                file_backup(info_syst=info_syst, orig_path=_conf_path, mode="init")
            # --- bluetooth: 50-bluez.conf ------------------------------------
            # headset disabled
            _conf_path: Path = addpath(
                base=_tget_path,
                path=Path("/etc/wireplumber/wireplumber.conf.d/50-bluez.conf"),
            )
            file_backup(info_syst=info_syst, orig_path=_conf_path)
            file_origin(info_syst=info_syst, orig_path=_conf_path)
            _read_text: str = (
                fread(src_path=_conf_path, text=True) + "\n"
                if _conf_path.exists()
                else ""
            )
            if "monitor.bluez.properties" not in _read_text:
                _writ_text: str = cat(r"""
					monitor.bluez.properties = {
					  bluez5.headset-roles  = "[ ]"
					  bluez5.hfphsp-backend = "none"
					}
		
					monitor.bluez.rules = [
					  {
					    matches = [
					      {
					        node.name = "~bluez_input.*"
					      }
					      {
					        node.name = "~bluez_output.*"
					      }
					    ]
					    actions = {
					      update-props = {
					        bluez5.auto-connect = "[ a2dp_sink ]"
					        bluez5.hw-volume    = "[ a2dp_sink ]"
					      }
					    }
					  }
					]
				""")  # noqa: E101, E501
                fwrite(
                    dest_path=_conf_path,
                    data=_writ_text,
                    text=True,
                    backup=False,
                    append=True,
                )
                file_backup(info_syst=info_syst, orig_path=_conf_path, mode="init")
        # --- service restart -------------------------------------------------
        if not info_syst.data.tget_chrt:
            restart_user_service(srvc_name=_srvc_name)
    except (OSError, Exception) as e:  # noqa: BLE001
        handle_fatal_error(_caller, e)


