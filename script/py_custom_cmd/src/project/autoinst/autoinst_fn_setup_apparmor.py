# --- python library ----------------------------------------------------------
import shutil
from pathlib import Path
from subprocess import CompletedProcess

# --- my library --------------------------------------------------------------
from common.utils import (
    debug_logger,
    get_caller_name,
    handle_fatal_error,
    message_info,
    run_subprocess,
)


# --- import module -----------------------------------------------------------
# --- class and function ------------------------------------------------------
@debug_logger
def setup_apparmor(info_syst) -> None:
    _caller = get_caller_name()
    _data = info_syst.data
    _tget_path: Path = getattr(_data, "tget_path", None)
    # --- check command -------------------------------------------------------
    if not shutil.which("aa-enabled"):
        message_info(_caller, f"{'skip':<10}:apparmor", omit=True)
        return
    try:
        message_info(_caller, f"{'setup':<10}:apparmor", omit=True)
        _tags_text: str = "# Generated by user script"
        # --- check command ---------------------------------------------------
        _shel_comd: str = r"aa-status || true"
        _result: CompletedProcess = run_subprocess(_shel_comd)
        if _result.returncode != 0 and _result.stderr:
            print(_result.stderr)
    except (OSError, Exception) as e:  # noqa: BLE001
        handle_fatal_error(_caller, e)


