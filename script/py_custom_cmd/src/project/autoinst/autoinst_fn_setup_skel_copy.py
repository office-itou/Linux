# --- python library ----------------------------------------------------------
import shutil
from pathlib import Path

# --- my library --------------------------------------------------------------
from common.utils import (
    addpath,
    debug_logger,
    delpath,
    get_caller_name,
    handle_fatal_error,
    message_info,
)


# --- import module -----------------------------------------------------------
# --- class and function ------------------------------------------------------
@debug_logger
def setup_skel_copy(info_syst) -> None:
    _caller = get_caller_name()
    _data = info_syst.data
    _tget_path: Path = getattr(_data, "tget_path", None)
    # --- check directory -----------------------------------------------------
    _skel_path: Path = addpath(base=_tget_path, path=Path("/etc/skel"))
    if not _skel_path.exists():
        message_info(_caller, f"{'skip':<10}:skel copy", omit=True)
        return
    try:
        message_info(_caller, f"{'setup':<10}:skel copy", omit=True)
        _tags_text: str = "# Generated by user script"
        # --- distribute to existing users ------------------------------------
        _root_path: Path = addpath(base=_tget_path, path=Path("/root"))
        _home_path: Path = addpath(base=_tget_path, path=Path("/home"))
        _home_list: list[Path] = sorted(list(_home_path.glob(r"*")))
        for _dirs_path in [_root_path, *_home_list]:
            if not _dirs_path.exists():
                print(f"{'skip':<10}:{_dirs_path}")
                continue
            _user_name = _dirs_path.owner()
            _grup_name = _dirs_path.group()
            print(f"{'setup':<10}:{_dirs_path}({_user_name}:{_grup_name})")
            _skel_list: list[Path] = sorted(list(_skel_path.rglob(r"*")))
            for _srcs_path in _skel_list:
                _dest_path: Path = _dirs_path / _srcs_path.relative_to(_skel_path)
                if _srcs_path.is_file():
                    print(f"{'copy':<10}:{_dest_path}")
                    shutil.copy2(_srcs_path, _dest_path)
                elif _srcs_path.is_dir():
                    print(f"{'mkdir':<10}:{_dest_path}")
                    _dest_path.mkdir(mode=0o755, parents=True, exist_ok=True)
                elif _srcs_path.is_symlink:
                    print(f"{'ln -s':<10}:{_dest_path}")
                    _tget_path = delpath(base=_tget_path, path=_srcs_path)
                    _dest_path.symlink_to(
                        target=_tget_path, target_is_directory=bool(_srcs_path.is_dir())
                    )
                else:
                    print(f"{'unknown':<10}:{_srcs_path}")
                    continue
                shutil.chown(path=_dest_path, user=_user_name, group=_grup_name)

    except (OSError, Exception) as e:  # noqa: BLE001
        handle_fatal_error(_caller, e)
