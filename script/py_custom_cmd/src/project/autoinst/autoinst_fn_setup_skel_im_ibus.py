# --- python library ----------------------------------------------------------
import os
import shutil
from pathlib import Path
from subprocess import CompletedProcess

# --- my library --------------------------------------------------------------
from common.utils import (
    addpath,
    cat,
    debug_logger,
    fwrite,
    get_caller_name,
    handle_fatal_error,
    message_info,
    run_subprocess,
)

# --- import module -----------------------------------------------------------
from autoinst_fn_file_backup import file_backup, file_origin


# --- class and function ------------------------------------------------------
@debug_logger
def setup_skel_im_ibus(info_syst) -> None:
    _caller = get_caller_name()
    _data = info_syst.data
    _tget_path: Path = getattr(_data, "tget_path", None)
    try:
        message_info(_caller, f"{'setup':<10}:skeleton im fcitx5", omit=True)
        _tags_text: str = "# Generated by user script"
        _envs_list: dict[str, str] = os.environ.copy()
        # --- ibus ------------------------------------------------------------
        if shutil.which("ibus"):
            _srcs_list: list[str] = ["('xkb', 'jp')"]
            _dirs_path: Path = addpath(
                base=_tget_path, path=Path("/usr/share/ibus-mozc")
            )
            if _dirs_path and _dirs_path.exists() and _dirs_path.is_dir():
                message_info(_caller, f"{'info':<10}:ibus-mozc", omit=True)
                _srcs_list.append("('ibus', 'mozc-jp')")
            _dirs_path: Path = addpath(
                base=_tget_path, path=Path("/usr/share/ibus-anthy")
            )
            if _dirs_path and _dirs_path.exists() and _dirs_path.is_dir():
                message_info(_caller, f"{'info':<10}:ibus-anthy", omit=True)
                _srcs_list.append("('ibus', 'anthy')")
            _srcs_prm: str = ", ".join(_srcs_list)
            if _srcs_prm:
                message_info(_caller, f"{'info':<10}:{_srcs_prm}", omit=True)
                _outp_dirs: Path = addpath(
                    base=_tget_path, path=Path("/etc/dconf/db/local")
                )
                _isrc_path = f"{_outp_dirs}.d/00-user-desktop-input-sources"
                file_backup(info_syst=info_syst, orig_path=_isrc_path)
                file_origin(info_syst=info_syst, orig_path=_isrc_path)
                _writ_text: str = cat(rf"""
					[org/gnome/desktop/input-sources]
					sources=[{_srcs_prm}]
				""")  # noqa: E101, E501
                fwrite(dest_path=_isrc_path, data=_writ_text, text=True, backup=False)
                file_backup(info_syst=info_syst, orig_path=_isrc_path, mode="init")
                _envs_list: dict[str, str] = os.environ.copy()
                _envs_list["_OUTP_DIRS"] = str(_outp_dirs)
                _envs_list["_ISRC_PATH"] = str(_isrc_path)
                _shel_comd: str = r"""
                    dconf compile "${_outp_dirs}" "${_ISRC_PATH%/*}" || true
                """
                _result: CompletedProcess = run_subprocess(_shel_comd, env=_envs_list)
                if _result.returncode != 0 and _result.stderr:
                    print(_result.stderr)
    except (OSError, Exception) as e:  # noqa: BLE001
        handle_fatal_error(_caller, e)


