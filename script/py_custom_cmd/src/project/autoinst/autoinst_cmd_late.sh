		fnFile_backup "${__PATH}" "init"	# backup initial file
	fi
	unset __NAME __VERS __DEFS __BOPT __SLNX __APAR __LINE __ENTR __WORK __PATH __CONF

	# --- complete ------------------------------------------------------------
	fnMsgout "${_PROG_NAME:-}" "complete" "[${__FUNC_NAME}]" 
	unset __FUNC_NAME
}