# -----------------------------------------------------------------------------
# descript: service
#   input :            : unused
#   output:   stdout   : message
#   return:            : unused
fnSetup_service() {
	__FUNC_NAME="fnSetup_service"
	fnMsgout "${_PROG_NAME:-}" "start" "[${__FUNC_NAME}]"

	# --- mask ----------------------------------------------------------------
	set -f
	set --
	for __LIST in \
		chronyd.service \
		avahi-daemon.service \
		brltty.service \
		nmb.service \
		nmbd.service \
		winbind.service \
		wicked.service \
		systemd-networkd.service \
		systemd-networkd-wait-online.service
	do
		__STAT="$(systemctl is-enabled "${__LIST}" || true)"
		[ "${__STAT:-}" = "alias" ] && continue
		if [ ! -e "${_DIRS_TGET:-}/etc/systemd/system/${__LIST}"     ] \
		&& [ ! -e "${_DIRS_TGET:-}/lib/systemd/system/${__LIST}"     ] \
		&& [ ! -e "${_DIRS_TGET:-}/usr/lib/systemd/system/${__LIST}" ]; then
			fnMsgout "${_PROG_NAME:-}" "not found (mask)" "${__LIST}"
			continue
		elif   [ -e "${_DIRS_TGET:-}/etc/systemd/system/${__LIST}"     ]; then
			if [ -d "${_DIRS_TGET:-}/etc/systemd/system/${__LIST}"     ] \
			|| [ -L "${_DIRS_TGET:-}/etc/systemd/system/${__LIST}"     ]; then
				fnMsgout "${_PROG_NAME:-}" "not found (mask)" "${__LIST}"
				continue
			fi
		fi
		fnMsgout "${_PROG_NAME:-}" "mask" "${__LIST}"
		set -- "$@" "${__LIST}"
	done 
	set +f
	[ $# -gt 0 ] && systemctl mask "$@"
	[ -z "${_TGET_CHRT:-}" ] && systemctl --quiet daemon-reload
	# --- enable --------------------------------------------------------------
	set -f
	set --
	for __LIST in \
		apparmor.service \
		auditd.service \
		firewalld.service \
		clamav-freshclam.service \
		clamav-daemon.service \
		NetworkManager.service \
		systemd-resolved.service \
		dnsmasq.service \
		systemd-timesyncd.service \
		open-vm-tools.service \
		vmtoolsd.service \
		ssh.service \
		sshd.service \
		apache2.service \
		httpd.service \
		smb.service \
		smbd.service \
		nfs-server.service \
		nbdkit.socket
	do
		__STAT="$(systemctl is-enabled "${__LIST}" || true)"
		if [ "${__STAT:-}" = "alias" ]; then
			fnMsgout "${_PROG_NAME:-}" "alias" "${__LIST}"
			continue
		fi
		if [ ! -e "${_DIRS_TGET:-}/etc/systemd/system/${__LIST}"     ] \
		&& [ ! -e "${_DIRS_TGET:-}/lib/systemd/system/${__LIST}"     ] \
		&& [ ! -e "${_DIRS_TGET:-}/usr/lib/systemd/system/${__LIST}" ]; then
			fnMsgout "${_PROG_NAME:-}" "not found (enable)" "${__LIST}"
		continue
		elif   [ -e "${_DIRS_TGET:-}/etc/systemd/system/${__LIST}"     ]; then
			if [ -d "${_DIRS_TGET:-}/etc/systemd/system/${__LIST}"     ] \
			|| [ -L "${_DIRS_TGET:-}/etc/systemd/system/${__LIST}"     ]; then
				fnMsgout "${_PROG_NAME:-}" "not found (enable)" "${__LIST}"
				continue
			fi
		fi
		fnMsgout "${_PROG_NAME:-}" "enable" "${__LIST}"
		set -- "$@" "${__LIST}"
	done 
	set +f
	[ $# -gt 0 ] && systemctl enable "$@"
	[ -z "${_TGET_CHRT:-}" ] && systemctl --quiet daemon-reload
	# --- service restart -----------------------------------------------------
	if [ -z "${_TGET_CHRT:-}" ] && [ $# -gt 0 ]; then
		for __SRVC in "$@"
		do
#			systemctl --quiet is-active "${__SRVC}" || continue
			fnMsgout "${_PROG_NAME:-}" "restart" "${__SRVC}"
			if systemctl --quiet restart "${__SRVC}"; then
				fnMsgout "${_PROG_NAME:-}" "success" "${__SRVC}"
			else
				fnMsgout "${_PROG_NAME:-}" "failed" "${__SRVC}"
			fi
		done
	fi
	unset __LIST __STAT __SRVC

	# --- complete ------------------------------------------------------------
	fnMsgout "${_PROG_NAME:-}" "complete" "[${__FUNC_NAME}]" 
	unset __FUNC_NAME
}

