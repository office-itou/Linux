# --- python library ----------------------------------------------------------
import os
import shutil
from pathlib import Path

# --- my library --------------------------------------------------------------
from common.utils import (
    addpath,
    cat,
    debug_logger,
    fread,
    fwrite,
    get_caller_name,
    handle_fatal_error,
    message_alert,
    message_info,
    run_subprocess,
)

# --- import module -----------------------------------------------------------
from autoinst_fn_file_backup import file_backup, file_origin


# --- class and function ------------------------------------------------------
@debug_logger
def setup_netplan(info_syst) -> None:
    _caller = get_caller_name()
    _data = info_syst.data
    _tget_path: Path = getattr(_data, "tget_path", None)
    # --- check command -------------------------------------------------------
    if not shutil.which("netplan"):
        message_info(_caller, f"{'skip':<10}:netplan", omit=True)
        return
    try:
        message_info(_caller, f"{'setup':<10}:netplan", omit=True)
        _tags_text: str = "# Generated by user script"
        # --- configures ------------------------------------------------------
        if shutil.which("nmcli"):
            # --- with network manager ----------------------------------------
            _npln_path: Path = addpath(base=_tget_path, path=Path("/etc/netplan"))
            for _conf_path in _npln_path.glob("*.yaml"):
                file_backup(info_syst=info_syst, orig_path=_conf_path)
                message_info(_caller, f"{'remove':<10}:{_conf_path}", omit=True)
                _conf_path.unlink()
            # --- 99-network-config-all.yaml --------------------------------------
            _conf_path: Path = addpath(
                base=_tget_path, path=Path("/etc/netplan/99-network-manager-all.yaml")
            )
            file_backup(info_syst=info_syst, orig_path=_conf_path)
            file_origin(info_syst=info_syst, orig_path=_conf_path)
            _read_text: str = (
                fread(src_path=_conf_path, text=True) + "\n"
                if _conf_path.exists()
                else ""
            )
            if _tags_text not in _read_text:
                _writ_text: str = cat(rf"""
					{_tags_text}
					network:
					  version: 2
					  renderer: NetworkManager
				""")  # noqa: E101
                fwrite(
                    dest_path=_conf_path,
                    data=_writ_text,
                    text=True,
                    backup=False,
                    append=True,
                )
                os.chmod(path=_conf_path, mode=0o600)
                file_backup(info_syst=info_syst, orig_path=_conf_path, mode="init")
            # --- 99-disable-network-config.cfg -------------------------------
            _conf_path: Path = addpath(
                base=_tget_path,
                path=Path("/etc/cloud/cloud.cfg.d/99-disable-network-config.cfg"),
            )
            file_backup(info_syst=info_syst, orig_path=_conf_path)
            file_origin(info_syst=info_syst, orig_path=_conf_path)
            _writ_text: str = r"network: {config: disabled}"
            fwrite(dest_path=_conf_path, data=_writ_text, text=True, backup=False)
            file_backup(info_syst=info_syst, orig_path=_conf_path, mode="init")
        else:
            _conf_path: Path = addpath(
                base=_tget_path,
                path=Path(f"/etc/netplan/99-network-config-{_data.nics_name}.yaml"),
            )
            file_backup(info_syst=info_syst, orig_path=_conf_path)
            file_origin(info_syst=info_syst, orig_path=_conf_path)
            _writ_text: str = cat(rf"""
				network:
					version: 2
					renderer: networkd
					ethernets:
					${_data.nics_name}:
			""")  # noqa: E101
            if _data.ipv4_auto:
                _writ_text += cat(r"""
					dhcp4: true
					dhcp6: true
					ipv6-privacy: true
				""")  # noqa: E101
            else:
                _writ_text += cat(rf"""
					addresses:
					- ${_data.nics_cidr}
					routes:
					- to: default
					via: ${_data.nics_gway}
					nameservers:
					search:
					- ${_data.nics_wgrp}
					addresses:
					- ${_data.nics_nsvr}
					dhcp4: false
					dhcp6: true
					ipv6-privacy: true
				""")  # noqa: E101
            fwrite(dest_path=_conf_path, data=_writ_text, text=True, backup=False)
            os.chmod(path=_conf_path, mode=0o600)
            file_backup(info_syst=info_syst, orig_path=_conf_path, mode="init")
        # --- netplan ---------------------------------------------------------
        _shel_comd: str = r"netplan status"
        _result = run_subprocess(_shel_comd)
        if _result.returncode == 0:
            _shel_comd: str = r"netplan apply"
            _result = run_subprocess(_shel_comd)
            if _result.returncode == 0:
                message_info(_caller, f"{'success':<10}:{_shel_comd}", omit=True)
            else:
                message_alert(_caller, f"{'failed':<10}:{_shel_comd}", omit=True)
    except (OSError, Exception) as e:  # noqa: BLE001
        handle_fatal_error(_caller, e)


