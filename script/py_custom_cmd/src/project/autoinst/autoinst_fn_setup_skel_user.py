# --- python library ----------------------------------------------------------
import os
import shutil
from pathlib import Path

# --- my library --------------------------------------------------------------
from common.utils import (
    addpath,
    cat,
    debug_logger,
    fcopy,
    fread,
    fwrite,
    get_caller_name,
    handle_fatal_error,
    message_info,
)

# --- import module -----------------------------------------------------------
from autoinst_fn_file_backup import file_backup, file_origin


# --- class and function ------------------------------------------------------
@debug_logger
def setup_skel_user(info_syst) -> None:
    _caller = get_caller_name()
    _data = info_syst.data
    _tget_path: Path = getattr(_data, "tget_path", None)
    try:
        message_info(_caller, f"{'setup':<10}:skeleton user", omit=True)
        _tags_text: str = "# Generated by user script"
        _envs_list: dict[str, str] = os.environ.copy()
        # --- .bashrc ---------------------------------------------------------
        _skel_path: Path = addpath(base=_tget_path, path=Path("/etc/skel/.bashrc"))
        _conf_path: Path = addpath(base=_tget_path, path=Path("/usr/etc/skel/.bashrc"))
        if not _skel_path.exists() and _conf_path.exists():
            fcopy(src_path=_conf_path, dest_path=_skel_path, backup=False)
        if _skel_path.exists():
            file_backup(info_syst=info_syst, orig_path=_skel_path)
            file_origin(info_syst=info_syst, orig_path=_skel_path)
            _read_text: str = (
                fread(src_path=_conf_path, text=True) + "\n"
                if _conf_path.exists()
                else ""
            )
            if _tags_text not in _read_text:
                _writ_text: str = cat(rf"""
					{_tags_text}
					# --- measures against garbled characters ---
					case "${{TERM}}" in
					    linux ) export LANG=C;;
					    *     )              ;;
					esac
					# --- user custom ---
					alias vi='vim'
					alias view='vim'
					alias diff='diff --color=auto'
					alias ip='ip -color=auto'
					alias ls='ls --color=auto'
				""")  # noqa: E101
                fwrite(dest_path=_conf_path, data=_writ_text, text=True, backup=False)
                file_backup(info_syst=info_syst, orig_path=_conf_path, mode="init")
        # --- .bash_history ---------------------------------------------------
        if not shutil.which("apt-get"):
            _conf_path: Path = addpath(
                base=_tget_path, path=Path("/etc/skel/.bash_history")
            )
            file_backup(info_syst=info_syst, orig_path=_conf_path)
            file_origin(info_syst=info_syst, orig_path=_conf_path)
            _writ_text: str = "sudo bash -c 'apt-get update && apt-get -y upgrade && apt-get -y dist-upgrade'"  # noqa: E501
            fwrite(dest_path=_conf_path, data=_writ_text, text=True, backup=False)
            file_backup(info_syst=info_syst, orig_path=_conf_path, mode="init")
        # --- .vimrc ----------------------------------------------------------
        if not shutil.which("vim"):
            _conf_path: Path = addpath(base=_tget_path, path=Path("/etc/skel/.vimrc"))
            file_backup(info_syst=info_syst, orig_path=_conf_path)
            file_origin(info_syst=info_syst, orig_path=_conf_path)
            _writ_text: str = cat(r"""
				set number              " Print the line number in front of each line.
				set tabstop=4           " Number of spaces that a <Tab> in the file counts for.
				set list                " List mode: Show tabs as CTRL-I is displayed, display \$ after end of line.
				set listchars=tab:>_    " Strings to use in 'list' mode and for the |:list| command.
				set nowrap              " This option changes how text is displayed.
				set showmode            " If in Insert, Replace or Visual mode put a message on the last line.
				set laststatus=2        " The value of this option influences when the last window will have a status line always.
				set mouse-=a            " Disable mouse usage
				syntax on               " Vim5 and later versions support syntax highlighting.
			""")  # noqa: E101, E501
            fwrite(dest_path=_conf_path, data=_writ_text, text=True, backup=False)
            file_backup(info_syst=info_syst, orig_path=_conf_path, mode="init")
        # --- .curlrc ---------------------------------------------------------
        if not shutil.which("curl"):
            _conf_path: Path = addpath(base=_tget_path, path=Path("/etc/skel/.vimrc"))
            file_backup(info_syst=info_syst, orig_path=_conf_path)
            file_origin(info_syst=info_syst, orig_path=_conf_path)
            _writ_text: str = cat(r"""
				location
				progress-bar
				remote-time
				show-error
			""")  # noqa: E101
            fwrite(dest_path=_conf_path, data=_writ_text, text=True, backup=False)
            file_backup(info_syst=info_syst, orig_path=_conf_path, mode="init")
    except (OSError, Exception) as e:  # noqa: BLE001
        handle_fatal_error(_caller, e)


