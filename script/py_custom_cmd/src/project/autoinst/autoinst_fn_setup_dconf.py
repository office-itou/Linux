# --- python library ----------------------------------------------------------
import os
import shutil
from pathlib import Path
from subprocess import CompletedProcess

# --- my library --------------------------------------------------------------
from common.utils import (
    addpath,
    cat,
    debug_logger,
    fread,
    fwrite,
    get_caller_name,
    handle_fatal_error,
    message_info,
    run_subprocess,
)

# --- import module -----------------------------------------------------------
from autoinst_fn_file_backup import file_backup, file_origin


# --- class and function ------------------------------------------------------
@debug_logger
def setup_dconf(info_syst) -> None:
    _caller = get_caller_name()
    _data = info_syst.data
    _tget_path: Path = getattr(_data, "tget_path", None)
    # --- check command -------------------------------------------------------
    if not shutil.which("dconf"):
        message_info(_caller, f"{'skip':<10}:dconf", omit=True)
        return
    try:
        message_info(_caller, f"{'setup':<10}:dconf", omit=True)
        _tags_text: str = "# Generated by user script"
        # --- /etc/dconf/profile/user -----------------------------------------
        _conf_path: Path = addpath(
            base=_tget_path, path=Path("/etc/dconf/profile/user")
        )
        file_backup(info_syst=info_syst, orig_path=_conf_path)
        file_origin(info_syst=info_syst, orig_path=_conf_path)
        _read_text: str = (
            fread(src_path=_conf_path, text=True) + "\n" if _conf_path.exists() else ""
        )
        _writ_list: list[str] = []
        for _find_text in [r"user-db:user", r"system-db:local"]:
            if _find_text in _read_text:
                continue
            _writ_list.append(_find_text)
        _writ_text: str = " ".join(_writ_list)
        if _writ_text:
            fwrite(
                dest_path=_conf_path,
                data=_writ_text,
                text=True,
                backup=False,
                append=True,
            )
            file_backup(info_syst=info_syst, orig_path=_conf_path, mode="init")
        # --- compile ---------------------------------------------------------
        _outp_dirs: str = "/etc/dconf/db/local"
        _envs_list: dict[str, str] = os.environ.copy()
        _envs_list["_OUTP_DIRS"] = str(_outp_dirs)
        _envs_list["_CONF_PATH"] = str(_conf_path)
        _shel_comd: str = r'dconf compile "${_OUTP_DIRS:?}" "${_CONF_PATH%/*}" || true'
        _result: CompletedProcess = run_subprocess(_shel_comd, env=_envs_list)
        if _result.returncode != 0 and _result.stderr:
            print(_result.stderr)
        # --- desktop/session -------------------------------------------------
        _conf_path: Path = Path(f"{_outp_dirs}.d/00-user-desktop-session")
        file_backup(info_syst=info_syst, orig_path=_conf_path)
        file_origin(info_syst=info_syst, orig_path=_conf_path)
        _read_text: str = (
            fread(src_path=_conf_path, text=True) + "\n" if _conf_path.exists() else ""
        )
        if "idle-delay=uint32" not in _read_text:
            _writ_text: str = cat(r"""
				[org/gnome/desktop/session]
				idle-delay=uint32 0
			""")
            fwrite(
                dest_path=_conf_path,
                data=_writ_text,
                text=True,
                backup=False,
                append=True,
            )
            file_backup(info_syst=info_syst, orig_path=_conf_path, mode="init")
        # --- terminal --------------------------------------------------------
        _uuid_text: str = ""
        _shel_comd: str = r"gsettings get org.gnome.Terminal.ProfilesList default"
        _result: CompletedProcess = run_subprocess(_shel_comd)
        if _result.returncode != 0 and _result.stderr:
            print(_result.stderr)
        else:
            _uuid_text: str = str(_result.stdout).strip("'")
        if _uuid_text:
            _conf_path: Path = Path(f"{_outp_dirs}.d/00-user-terminal")
            file_backup(info_syst=info_syst, orig_path=_conf_path)
            file_origin(info_syst=info_syst, orig_path=_conf_path)
            _read_text: str = (
                fread(src_path=_conf_path, text=True) + "\n"
                if _conf_path.exists()
                else ""
            )
            if _uuid_text not in _read_text:
                _rgbs_list: list[str] = [
                    r"'rgb(46,52,54)'",
                    r"'rgb(204,0,0)'",
                    r"'rgb(78,154,6)'",
                    r"'rgb(196,160,0)'",
                    r"'rgb(52,101,164)'",
                    r"'rgb(117,80,123)'",
                    r"'rgb(6,152,154)'",
                    r"'rgb(211,215,207)'",
                    r"'rgb(85,87,83)'",
                    r"'rgb(239,41,41)'",
                    r"'rgb(138,226,52)'",
                    r"'rgb(252,233,79)'",
                    r"'rgb(114,159,207)'",
                    r"'rgb(173,127,168)'",
                    r"'rgb(52,226,226)'",
                    r"'rgb(238,238,236)'",
                ]
                _writ_text: str = cat(rf"""
					[org/gnome/terminal/legacy/profiles:/:{_uuid_text}]
					default-size-columns=120
					default-size-rows=30
					font='Monospace 9'
					palette=[{", ".join(_rgbs_list)}]
					use-system-font=false
				""")
            # --- compile ---------------------------------------------------------
            _envs_list["_OUTP_DIRS"] = str(_outp_dirs)
            _envs_list["_CONF_PATH"] = str(_conf_path)
            _shel_comd: str = (
                r'dconf compile "${_OUTP_DIRS:?}" "${_CONF_PATH%/*}" || true'
            )
            _result: CompletedProcess = run_subprocess(_shel_comd, env=_envs_list)
            if _result.returncode != 0 and _result.stderr:
                print(_result.stderr)
    except (OSError, Exception) as e:  # noqa: BLE001
        handle_fatal_error(_caller, e)


