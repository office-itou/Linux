# --- python library ----------------------------------------------------------
import shutil
from pathlib import Path

# --- my library --------------------------------------------------------------
from common.utils import (
    cat,
    debug_logger,
    find_serivce,
    fwrite,
    get_caller_name,
    handle_fatal_error,
    message_info,
    restart_service,
)

# --- import module -----------------------------------------------------------
from autoinst_fn_file_backup import file_backup, file_origin


# --- class and function ------------------------------------------------------
@debug_logger
def setup_nbd(info_syst) -> None:
    _caller = get_caller_name()
    _data = info_syst.data
    _tget_path: Path = getattr(_data, "tget_path", None)
    # --- check command -------------------------------------------------------
    if not shutil.which("nbdkit"):
        message_info(_caller, f"{'skip':<10}:nbd", omit=True)
        return
    try:
        message_info(_caller, f"{'setup':<10}:nbd", omit=True)
        _tags_text: str = "# Generated by user script"
        # --- create socket ---------------------------------------------------
        _srvc_name: str = "nbdkit.service"
        _srvc_path: Path = find_serivce(tget_path=_tget_path, srvc_name=_srvc_name)
        if _srvc_path:
            _sock_path: Path = _srvc_path.with_suffix(".socket")
            file_backup(info_syst=info_syst, orig_path=_sock_path)
            file_origin(info_syst=info_syst, orig_path=_sock_path)
            _writ_text: str = cat(r"""
				[Unit]
				Description=NBDKit Network Block Device server
				[Socket]
				ListenStream=10809
				# Optional settings to detect dead clients:
				#KeepAlive=true
				#KeepAliveTimeSec=60
				#KeepAliveIntervalSec=10
				#KeepAliveProbes=5
				[Install]
				WantedBy=sockets.target
			""")
            fwrite(
                dest_path=_sock_path,
                data=_writ_text,
                text=True,
                backup=False,
                append=False,
            )
            file_backup(info_syst=info_syst, orig_path=_sock_path, mode="init")
            # --- create service ----------------------------------------------
            file_backup(info_syst=info_syst, orig_path=_srvc_path)
            file_origin(info_syst=info_syst, orig_path=_srvc_path)
            _writ_text: str = cat(rf"""
				ExecStart={shutil.which("nbdkit")} --exit-with-parent --readonly file cache=default fadvise=normal dir={str(_data.xnbd_path)}
				# Optional settings to run as non-root:
				#User=nbd
				#Group=nbd
			""")  # noqa: E501
            fwrite(
                dest_path=_sock_path,
                data=_writ_text,
                text=True,
                backup=False,
                append=False,
            )
            file_backup(info_syst=info_syst, orig_path=_sock_path, mode="init")
            # --- service restart ---------------------------------------------
            if not info_syst.data.tget_chrt:
                restart_service(srvc_name=_srvc_name)
    except (OSError, Exception) as e:  # noqa: BLE001
        handle_fatal_error(_caller, e)


