# --- python library ----------------------------------------------------------
import os
import shutil
from pathlib import Path
from subprocess import CompletedProcess

# --- my library --------------------------------------------------------------
from common.utils import (
    addpath,
    cat,
    daemon_reload,
    debug_logger,
    fread,
    fwrite,
    get_caller_name,
    handle_fatal_error,
    message_info,
    run_subprocess,
)

# --- import module -----------------------------------------------------------
from autoinst_fn_file_backup import file_backup, file_origin


# --- class and function ------------------------------------------------------
@debug_logger
def setup_vmware(info_syst) -> None:
    _caller = get_caller_name()
    _data = info_syst.data
    _tget_path: Path = getattr(_data, "tget_path", None)
    # --- check command -------------------------------------------------------
    if not shutil.which("vmware-hgfsclient"):
        message_info(_caller, f"{'skip':<10}:nbd", omit=True)
        return
    try:
        message_info(_caller, f"{'setup':<10}:nbd", omit=True)
        _tags_text: str = "# Generated by user script"
        # --- GNOME3 rendering issues -----------------------------------------
        _conf_path: Path = addpath(
            base=_tget_path, path=Path("/etc/environment.d/99vmware.conf")
        )
        if _conf_path and _conf_path.exists():
            file_backup(info_syst=info_syst, orig_path=_conf_path)
            file_origin(info_syst=info_syst, orig_path=_conf_path)
            _read_text: str = (
                fread(src_path=_conf_path, text=True) + "\n"
                if _conf_path.exists()
                else ""
            )
            if _tags_text not in _read_text:
                _writ_text: str = cat(rf"""
					{_tags_text}
					CLUTTER_PAINT=disable-clipped-redraws:disable-culling
				""")
                fwrite(
                    dest_path=_conf_path,
                    data=_writ_text,
                    text=True,
                    backup=False,
                    append=True,
                )
                file_backup(info_syst=info_syst, orig_path=_conf_path, mode="init")
        # --- check file system -----------------------------------------------
        _fsys_type: str = (
            "fuse.vmhgfs-fuse" if shutil.which("vmhgfs-fuse") else "vmhgfs"
        )
        # --- fstab -----------------------------------------------------------
        _fmat_parm: str = "{:<27} {:<35} {:<7} {:<27} {:<7} {}"
        _fmat_list: list[str] = [
            _fmat_parm.format(
                "# <file system>",
                "<mount point>",
                "<type>",
                "<options>",
                "<dump>",
                "<pass>",
            ),
            _fmat_parm.format(
                ".host:/",
                str(_data.hgfs_path),
                _fsys_type,
                "allow_other,defaults",
                "0",
                "0",
            ),
        ]
        _shel_comd: str = r"vmware-hgfsclient"
        _result: CompletedProcess = run_subprocess(_shel_comd)
        if _result.returncode != 0:
            _fmat_list: list[str] = [
                s if s[0:1] == "#" else f"#{s}" for s in _fmat_list
            ]
        _ftab_path: Path = addpath(base=_tget_path, path=Path("/etc/fstab"))
        _read_text = fread(src_path=_ftab_path, text=True)
        if ".host:/" not in _read_text:
            file_backup(info_syst=info_syst, orig_path=_ftab_path)
            file_origin(info_syst=info_syst, orig_path=_ftab_path)
            _head_list: list[str] = []
            _foot_list: list[str] = []
            _flag_bool: bool = False
            for _read in _read_text:
                if "/srv/" in _read:
                    _flag_bool = True
                if _flag_bool:
                    _foot_list.append(_read)
                else:
                    _head_list.append(_read)
            _writ_text = "\n".join(s for s in _head_list + _fmat_list + _foot_list)
            fwrite(dest_path=_ftab_path, data=_writ_text, text=True, backup=False)
            # --- check mount -------------------------------------------------
            message_info(_caller, f"{'info':<10}:check mount", omit=True)
            if not _data.tget_chrt:
                daemon_reload()
                _shel_comd: str = rf"mount {str(_data.hgfs_path)}"
                _result: CompletedProcess = run_subprocess(_shel_comd)
                if _result.returncode == 0:
                    message_info(
                        _caller, f"{'success':<10}:mounted:{_data.hgfs_path}", omit=True
                    )
                else:
                    message_info(
                        _caller,
                        f"{'failed':<10}:not mounted:{_data.hgfs_path}",
                        omit=True,
                    )
                    _envs_list = os.environ.copy()
                    _envs_list["_FTAB_PATH"] = _ftab_path
                    _shel_comd: str = r"""
                        sed -e "\%\.host:/% s/^/#/g" \
                            -i "${_FTAB_PATH:?}"
                    """
                    _result: CompletedProcess = run_subprocess(
                        _shel_comd, env=_envs_list
                    )
                if _result.returncode != 0 and _result.stderr:
                    print(_result.stderr)
            file_backup(info_syst=info_syst, orig_path=_ftab_path, mode="init")
    except (OSError, Exception) as e:  # noqa: BLE001
        handle_fatal_error(_caller, e, omit=False, raise_exit=False)
