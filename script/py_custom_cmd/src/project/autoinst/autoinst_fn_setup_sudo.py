# --- python library ----------------------------------------------------------
import os
import shutil
from pathlib import Path
from subprocess import CompletedProcess

# --- my library --------------------------------------------------------------
from common.utils import (
    addpath,
    cat,
    debug_logger,
    fcopy,
    fread,
    fwrite,
    get_caller_name,
    handle_fatal_error,
    message_info,
    run_subprocess,
)

# --- import module -----------------------------------------------------------
from autoinst_fn_file_backup import file_backup, file_origin


# --- class and function ------------------------------------------------------
@debug_logger
def setup_sudo(info_syst) -> None:
    _caller = get_caller_name()
    _data = info_syst.data
    _tget_path: Path = getattr(_data, "tget_path", None)
    # --- check command -------------------------------------------------------
    if not shutil.which("dconf"):
        message_info(_caller, f"{'skip':<10}:sudo", omit=True)
        return
    try:
        message_info(_caller, f"{'setup':<10}:sudo", omit=True)
        _tags_text: str = "# Generated by user script"
        # --- sudoers ---------------------------------------------------------
        message_info(_caller, f"{'setup':<10}:sudoers", omit=True)
        _conf_file: str = "/etc/sudoers"
        _conf_path: Path = addpath(base=_tget_path, path=Path(_conf_file))
        _tmpl_path: Path = addpath(base=_tget_path, path=(Path("/usr") / _conf_file))
        if not _conf_path.exists and _tmpl_path.exists():
            fcopy(src_path=_tmpl_path, dest_path=_conf_path, backup=False)
        if _conf_path.exists():
            file_backup(info_syst=info_syst, orig_path=_conf_path)
            file_origin(info_syst=info_syst, orig_path=_conf_path)
        _read_text: str = (
            fread(src_path=_conf_path, text=True) + "\n" if _conf_path.exists() else ""
        )
        _writ_text: str = "@includedir /etc/sudoers.d"
        if _writ_text not in _read_text:
            fwrite(
                dest_path=_conf_path,
                data=_writ_text,
                text=True,
                backup=False,
                append=True,
            )
        file_backup(info_syst=info_syst, orig_path=_conf_path, mode="init")
        # --- sudoers-local.work ----------------------------------------------
        message_info(_caller, f"{'setup':<10}:sudoers-local.work", omit=True)
        _grup_path: Path = addpath(base=_tget_path, path=Path("/etc/group"))
        _read_text: str = (
            fread(src_path=_grup_path, text=True) + "\n" if _grup_path.exists() else ""
        )
        _work_path: Path = _data.temp_path / "sudoers-local.work"
        _fmat_parm: str = "{:<6} {:<13} {}"
        for _find_text in ["sudo", "wheel"]:
            if _find_text in _read_text:
                _writ_text: str = cat(rf"""
					Defaults !targetpw
					#Defaults authenticate
					{_fmat_parm.format(r"root", r"ALL=(ALL:ALL)", r"ALL")}
					{_fmat_parm.format(_find_text, r"ALL=(ALL:ALL)", r"ALL")}
				""")
                fwrite(dest_path=_work_path, data=_writ_text, text=True, backup=False)
                file_backup(info_syst=info_syst, orig_path=_work_path, mode="init")
                break
        # --- sudoers-local -------------------------------------------------------
        message_info(_caller, f"{'setup':<10}:sudoers-local", omit=True)
        if _work_path.exists():
            _envs_list: dict[str, str] = os.environ.copy()
            _envs_list["_WORK_PATH"] = str(_work_path)
            _shel_comd: str = r"""
                visudo -q -c -f "${_WORK_PATH}"
            """
            _result: CompletedProcess = run_subprocess(_shel_comd, env=_envs_list)
            if _result.returncode != 0 and _result.stderr:
                print(_result.stderr)
                message_info(_caller, f"{'failed':<10}:{_work_path}", omit=True)
                _shel_comd: str = r'visudo -c -f "${_WORK_PATH:?}" || true'
                _result: CompletedProcess = run_subprocess(_shel_comd, env=_envs_list)
                if _result.returncode != 0 and _result.stderr:
                    print(_result.stderr)
            else:
                _lcal_path: Path = addpath(
                    base=_tget_path, path=Path("/etc/sudoers.d/sudoers-local")
                )
                fcopy(src_path=_work_path, dest_path=_lcal_path, backup=False)
                if _lcal_path.exists():
                    file_backup(info_syst=info_syst, orig_path=_lcal_path)
                    file_origin(info_syst=info_syst, orig_path=_lcal_path)
                _envs_list: dict[str, str] = os.environ.copy()
                _envs_list["_LCAL_PATH"] = str(_lcal_path)
                _shel_comd: str = r"""
                    chown --changes root:root "${_LCAL_PATH:?}"
                    chmod ---changes 0440 "${_LCAL_PATH:?}"
                """
                _result: CompletedProcess = run_subprocess(_shel_comd, env=_envs_list)
                if _result.returncode != 0 and _result.stderr:
                    print(_result.stderr)
                file_backup(info_syst=info_syst, orig_path=_lcal_path, mode="init")
                # --- sudoers -------------------------------------------------
                _work_path: Path = _data.temp_path / "sudoers.work"
                if _conf_path.exists():
                    file_backup(info_syst=info_syst, orig_path=_conf_path)
                    file_origin(info_syst=info_syst, orig_path=_conf_path)
                _envs_list["_CONF_PATH"] = str(_conf_path)
                _envs_list["_WORK_PATH"] = str(_work_path)
                _shel_comd: str = r"""
                    sed -e '/^Defaults[ \t]\+targetpw[ \t]*/ s/^/#/'                 \
                        -e '/^ALL[ \t]\+ALL=(ALL\(\|:ALL\))[ \t]\+ALL[ \t]*/ s/^/#/' \
                        ${_CONF_PATH:?}
                    >   ${_WORK_PATH:?}
                """
                _result: CompletedProcess = run_subprocess(_shel_comd, env=_envs_list)
                if _result.returncode != 0 and _result.stderr:
                    print(_result.stderr)
                file_backup(info_syst=info_syst, orig_path=_lcal_path, mode="init")
                _shel_comd: str = r"""
                    visudo -q -c -f "${_WORK_PATH}"
                """
                _result: CompletedProcess = run_subprocess(_shel_comd, env=_envs_list)
                if _result.returncode != 0 and _result.stderr:
                    print(_result.stderr)
                    message_info(_caller, f"{'failed':<10}:{_work_path}", omit=True)
                    _shel_comd: str = r'visudo -c -f "${_WORK_PATH:?}" || true'
                    _result: CompletedProcess = run_subprocess(
                        _shel_comd, env=_envs_list
                    )
                    if _result.returncode != 0 and _result.stderr:
                        print(_result.stderr)
                else:
                    fcopy(src_path=_work_path, dest_path=_conf_path, backup=False)
                    if _conf_path.exists():
                        file_backup(info_syst=info_syst, orig_path=_conf_path)
                        file_origin(info_syst=info_syst, orig_path=_conf_path)
                    _shel_comd: str = r"""
                        chown --changes root:root "${_CONF_PATH:?}"
                        chmod ---changes 0440 "${_CONF_PATH:?}"
                    """
                    _result: CompletedProcess = run_subprocess(
                        _shel_comd, env=_envs_list
                    )
                    if _result.returncode != 0 and _result.stderr:
                        print(_result.stderr)
                    file_backup(info_syst=info_syst, orig_path=_lcal_path, mode="init")
                    message_info(_caller, f"{'success':<10}:{_conf_path}", omit=True)
    except (OSError, Exception) as e:  # noqa: BLE001
        handle_fatal_error(_caller, e)


