# --- python library ----------------------------------------------------------
import os
import shutil
from pathlib import Path

# --- my library --------------------------------------------------------------
from common.utils import (
    addpath,
    cat,
    debug_logger,
    delpath,
    find_serivce,
    fwrite,
    get_caller_name,
    handle_fatal_error,
    message_info,
    restart_service,
    service_mask,
)

# --- import module -----------------------------------------------------------
from autoinst_fn_file_backup import file_backup, file_origin


# --- class and function ------------------------------------------------------
@debug_logger
def setup_resolv(info_syst) -> None:
    _caller = get_caller_name()
    _data = info_syst.data
    _tget_path: Path = getattr(_data, "tget_path", None)
    try:
        # --- check command ---------------------------------------------------
        _conf_path: Path = addpath(base=_tget_path, path=Path("/etc/resolv.conf"))
        if not shutil.which("resolvectl"):
            message_info(
                _caller, f"{'info':<10}:setup for non systemd-resolved", omit=True
            )
            if os.path.ismount(_conf_path):
                message_info(
                    _caller, f"{'caution':<10}:mount point:{_conf_path}", omit=True
                )
            else:
                file_backup(info_syst=info_syst, orig_path=_conf_path)
                file_origin(info_syst=info_syst, orig_path=_conf_path)
                if not _conf_path.is_symlink():
                    message_info(
                        _caller, f"{'caution':<10}:created:{_conf_path}", omit=True
                    )
                    _writ_text: str = cat(rf"""
						# Generated by user script
						search {_data.nwrk_wgrp}
						nameserver {_data.ipv6_lhst}
						nameserver {_data.ipv4_lhst}
					""")
                    fwrite(
                        dest_path=_conf_path, data=_writ_text, text=True, backup=False
                    )
                    file_backup(info_syst=info_syst, orig_path=_conf_path, mode="init")
        else:
            message_info(_caller, f"{'info':<10}:setup for systemd-resolved", omit=True)
            if os.path.ismount(_conf_path):
                message_info(
                    _caller, f"{'caution':<10}:mount point:{_conf_path}", omit=True
                )
            else:
                file_backup(info_syst=info_syst, orig_path=_conf_path)
                file_origin(info_syst=info_syst, orig_path=_conf_path)
                _conf_real = _conf_path.resolve()
                _stub_path: Path = addpath(
                    base=_tget_path, path=Path("/run/systemd/resolve/stub-resolv.conf")
                )
                if str(_conf_real) != str(_stub_path):
                    message_info(
                        _caller, f"{'caution':<10}:created:{_conf_path}", omit=True
                    )
                    os.remove(_conf_path)
                    _link_path = f"../{delpath(base=_tget_path, path=_stub_path)}"
                    message_info(
                        _caller, f"{'info':<10}:target :{_link_path}", omit=True
                    )
                    _conf_path.symlink_to(target=_link_path)
                    file_backup(info_syst=info_syst, orig_path=_conf_path, mode="init")
                    file_backup(info_syst=info_syst, orig_path=_stub_path, mode="init")
            # --- default.conf ------------------------------------------------
            _conf_path: Path = addpath(
                base=_tget_path, path=Path("/etc/systemd/resolved.conf.d/default.conf")
            )
            file_backup(info_syst=info_syst, orig_path=_conf_path)
            file_origin(info_syst=info_syst, orig_path=_conf_path)
            _writ_text: str = cat(rf"""
				[Resolve]
				DNS={_data.ipv4_lhst}
				#FallbackDNS=
				Domains={_data.nwrk_wgrp}
				#DNSSEC=no
				#DNSOverTLS=no
				MulticastDNS=yes
				LLMNR=yes
				#Cache=yes
				#CacheFromLocalhost=no
				#DNSStubListener=yes
				#DNSStubListenerExtra=
				ReadEtcHosts=no
				#ResolveUnicastSingleLabel=no
				#StaleRetentionSec=0
			""")
            fwrite(dest_path=_conf_path, data=_writ_text, text=True, backup=False)
            file_backup(info_syst=info_syst, orig_path=_conf_path, mode="init")
            # --- service restart ---------------------------------------------
            if not info_syst.data.tget_chrt:
                _srvc_name: str = "systemd-resolved.service"
                _srvc_path: Path = find_serivce(
                    tget_path=_tget_path, srvc_name=_srvc_name
                )
                if _srvc_path and _srvc_path.exists():
                    _svex_name: str = "avahi-daemon.service"
                    _svex_path: Path = find_serivce(
                        tget_path=_tget_path, srvc_name=_svex_name
                    )
                    if _svex_path and _svex_path.exists():
                        service_mask([_svex_path.name, f"{_svex_path.stem}.socket"])
                    restart_service(_srvc_name)
    except (OSError, Exception) as e:  # noqa: BLE001
        handle_fatal_error(_caller, e)


