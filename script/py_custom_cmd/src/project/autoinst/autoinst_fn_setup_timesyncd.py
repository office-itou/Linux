# --- python library ----------------------------------------------------------
from pathlib import Path

# --- my library --------------------------------------------------------------
from common.utils import (
    addpath,
    cat,
    debug_logger,
    find_serivce,
    fread,
    fwrite,
    get_caller_name,
    handle_fatal_error,
    message_info,
    restart_service,
)

# --- import module -----------------------------------------------------------
from autoinst_fn_file_backup import file_backup, file_origin


# --- class and function ------------------------------------------------------
@debug_logger
def setup_timesyncd(info_syst) -> None:
    _caller = get_caller_name()
    _data = info_syst.data
    _tget_path: Path = getattr(_data, "tget_path", None)
    # --- check service -------------------------------------------------------
    _srvc_name: str = "systemd-timesyncd.service"
    _srvc_path: Path = find_serivce(tget_path=_tget_path, srvc_name=_srvc_name)
    if not _srvc_path or not _srvc_path.exists():
        message_info(_caller, f"{'skip':<10}:timesyncd", omit=True)
        return
    try:
        message_info(_caller, f"{'setup':<10}:timesyncd", omit=True)
        _tags_text: str = "# Generated by user script"
        # --- timesyncd.conf --------------------------------------------------
        _conf_path: Path = addpath(
            base=_tget_path, path=Path("/etc/systemd/timesyncd.conf.d/local.conf")
        )
        file_backup(info_syst=info_syst, orig_path=_conf_path)
        file_origin(info_syst=info_syst, orig_path=_conf_path)
        _read_text: str = (
            fread(src_path=_conf_path, text=True) + "\n" if _conf_path.exists() else ""
        )
        if _tags_text not in _read_text:
            _writ_text: str = cat(rf"""
				{_tags_text}
				[Time]
				NTP={_data.ntps_addr}
				FallbackNTP={" ".join(_data.ntps_fbak)}
				PollIntervalMinSec=1h
				PollIntervalMaxSec=1d
				SaveIntervalSec=infinity
			""")
            fwrite(
                dest_path=_conf_path,
                data=_writ_text,
                text=True,
                backup=False,
                append=True,
            )
            file_backup(info_syst=info_syst, orig_path=_conf_path, mode="init")
        # --- service restart -------------------------------------------------
        if not info_syst.data.tget_chrt:
            restart_service(srvc_name=_srvc_name)
    except (OSError, Exception) as e:  # noqa: BLE001
        handle_fatal_error(_caller, e)


