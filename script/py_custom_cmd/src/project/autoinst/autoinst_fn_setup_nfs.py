# --- python library ----------------------------------------------------------
from pathlib import Path
from subprocess import CompletedProcess

# --- my library --------------------------------------------------------------
from common.utils import (
    addpath,
    cat,
    debug_logger,
    find_serivce,
    fwrite,
    get_caller_name,
    handle_fatal_error,
    message_info,
    restart_service,
    run_subprocess,
)

# --- import module -----------------------------------------------------------
from autoinst_fn_file_backup import file_backup, file_origin


# --- class and function ------------------------------------------------------
@debug_logger
def setup_nfs(info_syst) -> None:
    _caller = get_caller_name()
    _data = info_syst.data
    _tget_path: Path = getattr(_data, "tget_path", None)
    # --- check service -------------------------------------------------------
    _srvc_name: str = "nfs-server.service"
    _srvc_path: Path = find_serivce(tget_path=_tget_path, srvc_name=_srvc_name)
    if not _srvc_path or not _srvc_path.exists():
        message_info(_caller, f"{'skip':<10}:nfs-server", omit=True)
        return
    try:
        message_info(_caller, f"{'setup':<10}:nfs-server", omit=True)
        _tags_text: str = "# Generated by user script"
        # --- exports /srv ----------------------------------------------------
        _conf_file: str = "/etc/exports.d/srv.exports"
        _conf_path: Path = addpath(base=_tget_path, path=Path(_conf_file))
        file_backup(info_syst=info_syst, orig_path=_conf_path)
        file_origin(info_syst=info_syst, orig_path=_conf_path)
        _writ_text: str = cat(rf"""
			# exports file: "{_conf_file}"
			
			# --- ipv4 --------------------------------------------------------------------
			{str(_data.expo_path)} {_data.ipv4_uadr}.0/{_data.ipv4_prfx}(rw,sync,no_subtree_check,no_root_squash,fsid=0,crossmnt)
			{str(_data.xnfs_path)}/{str(_data.conf_path.name)} {_data.ipv4_uadr}.0/{_data.ipv4_prfx}(ro,sync,no_subtree_check,no_root_squash)
			{str(_data.xnfs_path)}/{str(_data.imgs_path.name)} {_data.ipv4_uadr}.0/{_data.ipv4_prfx}(ro,sync,no_subtree_check,no_root_squash)
			
			# --- ipv6 --------------------------------------------------------------------
			#{str(_data.expo_path)} {_data.ipv6_uadr}::/{_data.ipv6_prfx}(rw,sync,no_subtree_check,no_root_squash,fsid=0,crossmnt)
			#{str(_data.xnfs_path)}/{str(_data.conf_path.name)} {_data.ipv6_uadr}::/{_data.ipv6_prfx}(ro,sync,no_subtree_check,no_root_squash)
			#{str(_data.xnfs_path)}/{str(_data.imgs_path.name)} {_data.ipv6_uadr}::/{_data.ipv6_prfx}(ro,sync,no_subtree_check,no_root_squash)
			
			# --- link local --------------------------------------------------------------
			{str(_data.expo_path)} fe80::/{_data.link_prfx}(rw,sync,no_subtree_check,no_root_squash,fsid=0,crossmnt)
			{str(_data.xnfs_path)}/{str(_data.conf_path.name)} fe80::/{_data.link_prfx}(ro,sync,no_subtree_check,no_root_squash)
			{str(_data.xnfs_path)}/{str(_data.imgs_path.name)} fe80::/{_data.link_prfx}(ro,sync,no_subtree_check,no_root_squash)
			
			# --- server ------------------------------------------------------------------
			#{str(_data.expo_path)}/srv {_data.ipv4_uadr}.0/{_data.ipv4_prfx}(rw,sync,no_subtree_check,no_root_squash)
			#{str(_data.expo_path)}/srv {_data.ipv6_uadr}::/{_data.ipv6_prfx}(rw,sync,no_subtree_check,no_root_squash)
			#{str(_data.expo_path)}/srv fe80::/{_data.link_prfx}(rw,sync,no_subtree_check,no_root_squash)
			
			# --- eof ---------------------------------------------------------------------
		""")  # noqa: E501
        fwrite(
            dest_path=_conf_path,
            data=_writ_text,
            text=True,
            backup=False,
            append=True,
        )
        file_backup(info_syst=info_syst, orig_path=_conf_path, mode="init")
        # --- service restart -------------------------------------------------
        if not info_syst.data.tget_chrt:
            restart_service(srvc_name=_srvc_name)
            _shel_comd: str = r"""
                exportfs -v || true
                showmount -e || true
            """
            _result: CompletedProcess = run_subprocess(_shel_comd)
            if _result.returncode != 0:
                print(_result.stderr)
    except (OSError, Exception) as e:  # noqa: BLE001
        handle_fatal_error(_caller, e)


