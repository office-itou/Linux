# --- python library ----------------------------------------------------------
import os
import shutil
from pathlib import Path

# --- my library --------------------------------------------------------------
from common.utils import (
    addpath,
    debug_logger,
    file_backup,
    file_origin,
    find_serivce,
    fread,
    fwrite,
    get_caller_name,
    restart_user_service,
)


# --- import module -----------------------------------------------------------
# --- class and function ------------------------------------------------------
@debug_logger
def setup_connman(info_syst) -> None:
    _caller = get_caller_name()
    _data = info_syst.data
    _tget_path: Path = getattr(_data, "tget_path", None)
    # --- check service -------------------------------------------------------
    _srvc_name: str = "connman.service"
    _srvc_path: Path = find_serivce(tget_path=_tget_path, srvc_name=_srvc_name)
    if not _srvc_path or not _srvc_path.exists():
        return
    # --- main.conf -----------------------------------------------------------
    _tags_text: str = "# Generated by user script"
    _conf_path: Path = addpath(base=_tget_path, path=Path("/etc/connman/main.conf"))
    file_backup(info_syst=info_syst, orig_path=_conf_path)
    file_origin(info_syst=info_syst, orig_path=_conf_path)
    _read_text: str = fread(src_path=_conf_path, text=True)
    if _tags_text in _read_text:
        _writ_text: str = (
            f"{_read_text}"
            "\n"
            f"{_tags_text}\n"
            "AllowHostnameUpdates = false\n"
            "AllowDomainnameUpdates = false\n"
            "PreferredTechnologies = ethernet,wifi\n"
            "SingleConnectedTechnology = true\n"
        )
        fwrite(dest_path=_conf_path, data=_writ_text, text=True, backup=False)
        file_backup(info_syst=info_syst, orig_path=_conf_path, mode="init")
    # --- disable_dns_proxy.conf ----------------------------------------------
    _comd_path: Path = Path(shutil.which("connmand"))
    _conf_path: Path = addpath(
        base=_tget_path,
        path=Path("/etc/systemd/system/connman.service.d/disable_dns_proxy.conf"),
    )
    file_backup(info_syst=info_syst, orig_path=_conf_path)
    _writ_text: str = f"[Service]\nExecStart=\nExecStart={_comd_path} -n --nodnsproxy\n"
    fwrite(dest_path=_conf_path, data=_writ_text, text=True, backup=False)
    file_backup(info_syst=info_syst, orig_path=_conf_path, mode="init")
    # --- settings ------------------------------------------------------------
    _madr_text = _data.nics_madr.replace(":")
    _conf_path: Path = addpath(
        base=_tget_path,
        path=Path(f"/var/lib/connman/ethernet_{_madr_text}_cable/settings"),
    )
    file_backup(info_syst=info_syst, orig_path=_conf_path)
    _writ_text: str = (
        f"[ethernet_{_madr_text}_cable]\nName=Wired\nAutoConnect=true\nModified=\n"
    )
    if _data.ipv4_auto:
        _writ_text += (
            "IPv4.method=dhcp\n"
            "IPv4.DHCP.LastAddress=\n"
            "IPv6.method=auto\n"
            "IPv6.privacy=prefered\n"
        )
    else:
        _writ_text += (
            "IPv4.method=manual\n"
            f"IPv4.netmask_prefixlen={_data.nics_prfx}\n"
            f"IPv4.local_address={_data.nics_ipv4}\n"
            f"IPv4.gateway={_data.nics_gway}\n"
            "IPv6.method=auto\n"
            "IPv6.privacy=prefered\n"
            f"Nameservers={_data.nics_nsvr};\n"
            f"Domains={_data.nics_wgrp};\n"
            "IPv6.DHCP.DUID=\n"
        )
    fwrite(dest_path=_conf_path, data=_writ_text, text=True, backup=False)
    os.chmod(path=_conf_path, mode=0o600)
    file_backup(info_syst=info_syst, orig_path=_conf_path, mode="init")
    # --- service restart -----------------------------------------------------
    if not info_syst.data.tget_chrt:
        restart_user_service(srvc_name=_srvc_name)


