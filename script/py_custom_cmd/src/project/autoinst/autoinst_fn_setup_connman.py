# --- python library ----------------------------------------------------------
import shutil
from pathlib import Path

# --- my library --------------------------------------------------------------
from common.utils import (
    addpath,
    cat,
    debug_logger,
    find_serivce,
    fread,
    fwrite,
    get_caller_name,
    handle_fatal_error,
    message_info,
    restart_service,
)

# --- import module -----------------------------------------------------------
from autoinst_fn_file_backup import file_backup, file_origin


# --- class and function ------------------------------------------------------
@debug_logger
def setup_connman(info_syst) -> None:
    _caller = get_caller_name()
    _data = info_syst.data
    _tget_path: Path = getattr(_data, "tget_path", None)
    # --- check service -------------------------------------------------------
    _srvc_name: str = "connman.service"
    _srvc_path: Path = find_serivce(tget_path=_tget_path, srvc_name=_srvc_name)
    if not _srvc_path or not _srvc_path.exists():
        message_info(_caller, f"{'skip':<10}:connman", omit=True)
        return
    try:
        message_info(_caller, f"{'setup':<10}:connman", omit=True)
        _tags_text: str = "# Generated by user script"
        # --- main.conf -------------------------------------------------------
        _conf_path: Path = addpath(base=_tget_path, path=Path("/etc/connman/main.conf"))
        file_backup(info_syst=info_syst, orig_path=_conf_path)
        file_origin(info_syst=info_syst, orig_path=_conf_path)
        _read_text: str = (
            fread(src_path=_conf_path, text=True) + "\n" if _conf_path.exists() else ""
        )
        if _tags_text not in _read_text:
            _writ_text: str = cat(fr"""
				{_tags_text}
				AllowHostnameUpdates = false
				AllowDomainnameUpdates = false
				PreferredTechnologies = ethernet,wifi
				SingleConnectedTechnology = true
			""")
            fwrite(
                dest_path=_conf_path,
                data=_writ_text,
                text=True,
                backup=False,
                append=True,
            )
            file_backup(info_syst=info_syst, orig_path=_conf_path, mode="init")
        # --- disable_dns_proxy.conf ------------------------------------------
        _comd_path: Path = Path(shutil.which("connmand"))
        _conf_path: Path = addpath(
            base=_tget_path,
            path=Path("/etc/systemd/system/connman.service.d/disable_dns_proxy.conf"),
        )
        file_backup(info_syst=info_syst, orig_path=_conf_path)
        file_origin(info_syst=info_syst, orig_path=_conf_path)
        _writ_text: str = cat(fr"""
			[Service]
			ExecStart=
			ExecStart=${_comd_path} -n --nodnsproxy
		""")
        fwrite(dest_path=_conf_path, data=_writ_text, text=True, backup=False)
        file_backup(info_syst=info_syst, orig_path=_conf_path, mode="init")
        # --- settings --------------------------------------------------------
        _madr_text = _data.nwrk_madr.replace(":")
        _conf_path: Path = addpath(
            base=_tget_path,
            path=Path(f"/var/lib/connman/ethernet_{_madr_text}_cable/settings"),
        )
        file_backup(info_syst=info_syst, orig_path=_conf_path)
        file_origin(info_syst=info_syst, orig_path=_conf_path)
        _writ_text: str = cat(fr"""
			[ethernet_${_madr_text}_cable]
			Name=Wired
			AutoConnect=true
			Modified=
		""")
        if _data.ipv4_auto:
            _writ_text += cat(r"""
				IPv4.method=dhcp
				IPv4.DHCP.LastAddress=
				IPv6.method=auto
				IPv6.privacy=prefered
			""")
        else:
            _writ_text += cat(fr"""
				IPv4.method=manual
				IPv4.netmask_prefixlen=${_data.ipv4_prfx}
				IPv4.local_address=${_data.ipv4_addr}
				IPv4.gateway=${_data.ipv4_gway}
				IPv6.method=auto
				IPv6.privacy=prefered
				Nameservers=${_data.ipv4_nsvr};
				Domains=${_data.nwrk_wgrp};
				IPv6.DHCP.DUID=
			""")
        fwrite(dest_path=_conf_path, data=_writ_text, text=True, backup=False)
        file_backup(info_syst=info_syst, orig_path=_conf_path, mode="init")
        # --- service restart -------------------------------------------------
        if not info_syst.data.tget_chrt:
            restart_service(srvc_name=_srvc_name)
    except (OSError, Exception) as e:  # noqa: BLE001
        handle_fatal_error(_caller, e)


