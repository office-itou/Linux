# --- python library ----------------------------------------------------------
import os
from pathlib import Path
from subprocess import CompletedProcess

# --- my library --------------------------------------------------------------
from common.utils import (
    addpath,
    cat,
    debug_logger,
    find_serivce,
    fread,
    fwrite,
    get_caller_name,
    handle_fatal_error,
    message_info,
    restart_service,
    run_subprocess,
)

# --- import module -----------------------------------------------------------
from autoinst_fn_file_backup import file_backup, file_origin


# --- class and function ------------------------------------------------------
@debug_logger
def setup_ssh(info_syst) -> None:
    _caller = get_caller_name()
    _data = info_syst.data
    _tget_path: Path = getattr(_data, "tget_path", None)
    # --- check service -------------------------------------------------------
    _srvc_list: list[str] = ["ssh.service", "sshd.service"]
    _srvc_path: Path = find_serivce(tget_path=_tget_path, srvc_list=_srvc_list)
    if not _srvc_path or not _srvc_path.exists():
        message_info(_caller, f"{'skip':<10}:ssh", omit=True)
        return
    try:
        _srvc_name = _srvc_path.name
        message_info(_caller, f"{'setup':<10}:{_srvc_name}", omit=True)
        _tags_text: str = "# Generated by user script"
        # --- default.conf ----------------------------------------------------
        _pswd_path: Path = addpath(base=_tget_path, path=Path("/etc/passwd"))
        _envs_list: dict[str, str] = os.environ.copy()
        _envs_list["_PSWD_PATH"] = str(_pswd_path)
        _shel_comd: str = r"""
            awk -F ':' 'BEGIN {ret="yes"}
            {
                if (($1 != "root") && ($4 >= 1000) && ($4 < "65534") && ($7 !~ /nologin|false/)) {
                    ret="no";
                    exit
                }
            }
            END {print ret}' "${_PSWD_PATH:-}"
        """  # noqa: E501
        _result: CompletedProcess = run_subprocess(_shel_comd, env=_envs_list)
        if _result.returncode != 0 and _result.stderr:
            print(_result.stderr)
        elif _result.stdout:
            _root_lgin: str = str(_result.stdout).strip("\n").strip() + r"\|"
            message_info(_caller, f"{'info':<10}:root login {_root_lgin}", omit=True)
            _conf_path: Path = addpath(
                base=_tget_path, path=Path("/etc/ssh/sshd_config.d/default.conf")
            )
            if _conf_path.exists():
                file_backup(info_syst=info_syst, orig_path=_conf_path)
                file_origin(info_syst=info_syst, orig_path=_conf_path)
                _read_text: str = (
                    fread(src_path=_conf_path, text=True) + "\n"
                    if _conf_path.exists()
                    else ""
                )
                if _tags_text not in _read_text:
                    _writ_text: str = cat(rf"""
						{_tags_text}
						
						# port number to listen to ssh
						#Port 22
						
						# ip address to accept connections
						#ListenAddress 0.0.0.0
						#ListenAddress ::
						
						# ssh protocol
						Protocol 2
						
						# whether to allow root login
						PermitRootLogin {_root_lgin}
						
						# configuring public key authentication
						#PubkeyAuthentication no
						
						# public key file location
						#AuthorizedKeysFile
						
						# setting password authentication
						PasswordAuthentication yes
						
						# configuring challenge-response authentication
						#ChallengeResponseAuthentication no
						
						# sshd log is output to /var/log/secure
						#SyslogFacility AUTHPRIV
						
						# specify log output level
						#LogLevel INFO
					""")
                    fwrite(
                        dest_path=_conf_path,
                        data=_writ_text,
                        text=True,
                        backup=False,
                        append=True,
                    )
                    file_backup(info_syst=info_syst, orig_path=_conf_path, mode="init")
                # --- service restart -----------------------------------------
                if not info_syst.data.tget_chrt:
                    restart_service(srvc_name=_srvc_name)
    except (OSError, Exception) as e:  # noqa: BLE001
        handle_fatal_error(_caller, e)


