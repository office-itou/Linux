# --- python library ----------------------------------------------------------
import os
import shutil
from pathlib import Path

# --- my library --------------------------------------------------------------
from common.utils import (
    addpath,
    cat,
    debug_logger,
    fwrite,
    get_caller_name,
    handle_fatal_error,
    message_info,
)

# --- import module -----------------------------------------------------------
from autoinst_fn_file_backup import file_backup, file_origin


# --- class and function ------------------------------------------------------
@debug_logger
def setup_skel_im_fcitx5(info_syst) -> None:
    _caller = get_caller_name()
    _data = info_syst.data
    _tget_path: Path = getattr(_data, "tget_path", None)
    try:
        message_info(_caller, f"{'setup':<10}:skeleton im fcitx5", omit=True)
        _tags_text: str = "# Generated by user script"
        _envs_list: dict[str, str] = os.environ.copy()
        # --- fcitx5 ----------------------------------------------------------
        if not shutil.which("fcitx5"):
            # --- .xinputrc ---------------------------------------------------
            _conf_path: Path = addpath(
                base=_tget_path, path=Path("/etc/skel/.xinputrc")
            )
            file_backup(info_syst=info_syst, orig_path=_conf_path)
            file_origin(info_syst=info_syst, orig_path=_conf_path)
            _writ_text: str = cat(r"""
				# im-config(8) generated on Sat, 14 Feb 2026 09:14:00 +0900
				run_im fcitx5
				# im-config signature: d9b9928f862c39723ce984af60025ad5  -
			""")  # noqa: E101, E501
            fwrite(dest_path=_conf_path, data=_writ_text, text=True, backup=False)
            file_backup(info_syst=info_syst, orig_path=_conf_path, mode="init")
            # --- .xprofile ---------------------------------------------------
            _conf_path: Path = addpath(
                base=_tget_path,
                path=Path("/etc/skel/.config/environment.d/99fcitx.conf"),
            )
            file_backup(info_syst=info_syst, orig_path=_conf_path)
            file_origin(info_syst=info_syst, orig_path=_conf_path)
            _writ_text: str = cat(r"""
				XMODIFIERS=@im=fcitx
				QT_IM_MODULE=fcitx
				#GTK_IM_MODULE=fcitx
				#SDL_IM_MODULE=fcitx
				#QT_IM_MODULES="wayland;fcitx"
				#CLUTTER_IM_MODULE=xim
				#IM_CONFIG_PHASE=
			""")  # noqa: E101, E501
            fwrite(dest_path=_conf_path, data=_writ_text, text=True, backup=False)
            file_backup(info_syst=info_syst, orig_path=_conf_path, mode="init")
            # --- profile -----------------------------------------------------
            _conf_path: Path = addpath(
                base=_tget_path, path=Path("/etc/skel/.config/fcitx5/profile")
            )
            file_backup(info_syst=info_syst, orig_path=_conf_path)
            file_origin(info_syst=info_syst, orig_path=_conf_path)
            _writ_text: str = cat(r"""
				[Groups/0]
				# Group Name
				Name=デフォルト
				# Layout
				Default Layout=jp
				# Default Input Method
				DefaultIM=mozc
				
				[Groups/0/Items/0]
				# Name
				Name=keyboard-jp
				# Layout
				Layout=
				
				[Groups/0/Items/1]
				# Name
				Name=mozc
				# Layout
				Layout=
				
				[Groups/0/Items/2]
				# Name
				Name=anthy
				# Layout
				Layout=
				
				[GroupOrder]
				0=デフォルト
				
			""")  # noqa: E101, E501
            fwrite(dest_path=_conf_path, data=_writ_text, text=True, backup=False)
            file_backup(info_syst=info_syst, orig_path=_conf_path, mode="init")
            # --- config ------------------------------------------------------
            _conf_path: Path = addpath(
                base=_tget_path, path=Path("/etc/skel/.config/fcitx5/config")
            )
            file_backup(info_syst=info_syst, orig_path=_conf_path)
            file_origin(info_syst=info_syst, orig_path=_conf_path)
            _writ_text: str = cat(r"""
				[Hotkey]
				# トリガーキーを押すたびに切り替える
				EnumerateWithTriggerKeys=True
				# 次の入力メソッドに切り替える
				EnumerateForwardKeys=
				# 前の入力メソッドに切り替える
				EnumerateBackwardKeys=
				# 切り替え時は第1入力メソッドをスキップする
				EnumerateSkipFirst=False
				
				[Hotkey/TriggerKeys]
				0=Control+space
				1=Zenkaku_Hankaku
				2=Hangul
				
				[Hotkey/AltTriggerKeys]
				0=Shift_L
				
				[Hotkey/EnumerateGroupForwardKeys]
				0=Super+space
				
				[Hotkey/EnumerateGroupBackwardKeys]
				0=Shift+Super+space
				
				[Hotkey/ActivateKeys]
				0=Hangul_Hanja
				
				[Hotkey/DeactivateKeys]
				0=Hangul_Romaja
				
				[Hotkey/PrevPage]
				0=Up
				
				[Hotkey/NextPage]
				0=Down
				
				[Hotkey/PrevCandidate]
				0=Shift+Tab
				
				[Hotkey/NextCandidate]
				0=Tab
				
				[Hotkey/TogglePreedit]
				0=Control+Alt+P
				
				[Behavior]
				# デフォルトで有効にする
				ActiveByDefault=False
				# 入力状態を共有する
				ShareInputState=No
				# アプリケーションにプリエディットを表示する
				PreeditEnabledByDefault=True
				# 入力メソッドを切り替える際に入力メソッドの情報を表示する
				ShowInputMethodInformation=True
				# フォーカスを変更する際に入力メソッドの情報を表示する
				showInputMethodInformationWhenFocusIn=False
				# 入力メソッドの情報をコンパクトに表示する
				CompactInputMethodInformation=True
				# 第1入力メソッドの情報を表示する
				ShowFirstInputMethodInformation=True
				# デフォルトのページサイズ
				DefaultPageSize=5
				# XKB オプションより優先する
				OverrideXkbOption=False
				# カスタム XKB オプション
				CustomXkbOption=
				# Force Enabled Addons
				EnabledAddons=
				# Force Disabled Addons
				DisabledAddons=
				# Preload input method to be used by default
				PreloadInputMethod=True
				# パスワード欄に入力メソッドを許可する
				AllowInputMethodForPassword=False
				# パスワード入力時にプリエディットテキストを表示する
				ShowPreeditForPassword=False
				# ユーザーデータを保存する間隔（分）
				AutoSavePeriod=30
				
				""")  # noqa: E101, E501
            fwrite(dest_path=_conf_path, data=_writ_text, text=True, backup=False)
            file_backup(info_syst=info_syst, orig_path=_conf_path, mode="init")
    except (OSError, Exception) as e:  # noqa: BLE001
        handle_fatal_error(_caller, e)


